# Regenerates test/golden/reference.jl from the current source tree.
#
# Only run this when a numerical change is intended and understood. The
# reference exists to catch unintended changes during refactoring.
#
#     julia --project=. test/golden/generate_reference.jl

include(joinpath(@__DIR__, "model.jl"))

function _commit()
    try
        return readchomp(`git -C $(@__DIR__) rev-parse --short HEAD`)
    catch
        return "unknown"
    end
end

function _write_reference(io, name, result)
    println(io, "const ", name, " = (")
    for k in keys(result)
        println(io, "    ", k, " = ", repr(getfield(result, k)), ",")
    end
    println(io, ")")
end

open(joinpath(@__DIR__, "reference.jl"), "w") do io
    println(io, "# Generated by test/golden/generate_reference.jl. Do not edit by hand.")
    println(io, "# Source commit: ", _commit())
    _write_reference(io, "GOLDEN_REFERENCE", golden_measure())
    println(io)
    _write_reference(io, "ASYM_REFERENCE", golden_measure(asymmetric_model().layers))
end

println("wrote ", joinpath(@__DIR__, "reference.jl"))
